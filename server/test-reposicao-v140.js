import assert from 'node:assert/strict';
import {reposicao} from '../src/pages/reposicao.js';
const item={frentesPrevistas:2,frentesConfirmadas:1,reference:{unidades:4},quantidadeConfirmada:2,state:'P'};
assert.deepEqual(reposicao(item),{height:2,units:2});
assert.deepEqual(reposicao({...item,quantidadeConfirmada:null}),{height:1,units:null});
assert.deepEqual(reposicao({...item,quantidadeConfirmada:1}),{height:1,units:3});
assert.deepEqual(reposicao({...item,state:'A',frentesConfirmadas:0}),{height:2,units:4});
console.log('Reposição: empilhados, quantidade desconhecida, irregular e ruptura aprovados.');
import {indicadoresSugeridos} from './frentes-revisao.js';
const raw={sku:'7891000000073',name:'Cream cheese 150g',candidateState:'P',state:'I',systemPrice:10.9,stock:200,frentesPrevistas:2,frentesCandidatas:1,reference:{colunas:2,unidades:4},observed:{colunas:1,unidades:2},quantidadeVisivel:null,quantidadeConfirmada:null};
const row={sku:raw.sku,state:'P',priceRead:10.9,quantidadeVisivel:null,frentesConfirmadas:null};
const occurrence=indicadoresSugeridos([raw],[row]).occurrences.find(o=>o.type==='Exposição parcial');
assert.equal(occurrence.stock,200);
assert.deepEqual(reposicao(occurrence),{height:2,units:2,estimated:true});
const corrected=indicadoresSugeridos([raw],[{...row,edited:true,frentesConfirmadas:1,quantidadeVisivel:2}]).occurrences[0];
assert.deepEqual(reposicao(corrected),{height:2,units:2});
const unknown=indicadoresSugeridos([raw],[{...row,edited:true,frentesConfirmadas:1}]).occurrences[0];
assert.deepEqual(reposicao(unknown),{height:1,units:null});
console.log('Fluxo preliminar: ocorrência com estoque 200, empilhamento estimado, correção manual e quantidade desconhecida aprovados.');
